def reliability(y: np.ndarray, probability: np.ndarray, bins: int = 10) -> list:
    """Group patients by predicted risk and count what actually happened.

    The reliability diagram, as a table. For each bin: how many patients,
    what the model promised on average, and what fraction of them had the
    event. A calibrated model puts those last two columns on top of each
    other.

    Bins are fixed-width over [0, 1] rather than equal-count, because
    equal-count bins hide the region where a model is most confident and
    most wrong - which is where the interesting failure lives.
    """
    if bins < 1:
        raise ValueError(f"bins must be at least 1, got {bins}")
    y = np.asarray(y, dtype=float)
    probability = np.asarray(probability, dtype=float)
    edges = np.linspace(0.0, 1.0, bins + 1)
    rows = []
    for index in range(bins):
        low, high = edges[index], edges[index + 1]
        inside = (probability >= low) & (probability < high if index < bins - 1
                                         else probability <= high)
        count = int(inside.sum())
        if not count:
            rows.append({"low": float(low), "high": float(high), "count": 0,
                         "predicted": float("nan"), "observed": float("nan")})
            continue
        rows.append({"low": float(low), "high": float(high), "count": count,
                     "predicted": float(probability[inside].mean()),
                     "observed": float(y[inside].mean())})
    return rows


def expected_calibration_error(y: np.ndarray, probability: np.ndarray,
                               bins: int = 10) -> float:
    """Average gap between promised and observed risk, weighted by bin size.

    One number for a reliability diagram. It is a weighted mean absolute
    error, so it cannot distinguish a model that is uniformly 5% too
    confident from one that is 20% wrong in one bin and right everywhere
    else - the demo shows both and says which is which.
    """
    rows = reliability(y, probability, bins=bins)
    total = sum(row["count"] for row in rows)
    if not total:
        return 0.0
    return float(sum(row["count"] * abs(row["predicted"] - row["observed"])
                     for row in rows if row["count"]) / total)


def brier_score(y: np.ndarray, probability: np.ndarray) -> float:
    """Mean squared error of the predicted probabilities.

    Unlike AUC it is a **proper scoring rule**: it is minimised only by
    reporting your true belief, so a model cannot improve it by shading
    its predictions towards the middle or the extremes.

    >>> round(brier_score(np.array([1.0, 0.0]), np.array([1.0, 0.0])), 6)
    0.0
    """
    y = np.asarray(y, dtype=float)
    probability = np.asarray(probability, dtype=float)
    return float(np.mean((probability - y) ** 2))


def brier_decomposition(y: np.ndarray, probability: np.ndarray,
                        bins: int = 10) -> dict:
    """Split the Brier score into reliability, resolution and uncertainty.

        Brier = reliability - resolution + uncertainty

    **Reliability** is the calibration error (lower is better).
    **Resolution** is how far the bins' outcome rates sit from the base
    rate — how much the model actually distinguishes patients (higher is
    better). **Uncertainty** is the base rate's own variance, which no
    model can change.

    The decomposition is the cleanest statement of what this day is
    about: calibration and discrimination are *separate terms*, and a
    model can be good at one while being poor at the other.
    """
    y = np.asarray(y, dtype=float)
    rows = reliability(y, probability, bins=bins)
    total = len(y)
    base_rate = float(y.mean())
    reliability_term = 0.0
    resolution_term = 0.0
    for row in rows:
        if not row["count"]:
            continue
        weight = row["count"] / total
        reliability_term += weight * (row["predicted"] - row["observed"]) ** 2
        resolution_term += weight * (row["observed"] - base_rate) ** 2
    uncertainty = base_rate * (1 - base_rate)
    return {"reliability": reliability_term, "resolution": resolution_term,
            "uncertainty": uncertainty,
            "brier": reliability_term - resolution_term + uncertainty}


def miscalibrate(probability: np.ndarray, power: float = 1.0,
                 shift: float = 0.0) -> np.ndarray:
    """Distort probabilities without changing their order.

    ``power`` raises the odds to a power - over-confident above 1, under
    below - and ``shift`` multiplies the odds by a constant. Both are
    strictly monotone, so **AUC is untouched by construction** and any
    change in calibration is the whole effect.

    This is the instrument for the day's central claim, and the reason it
    is a claim rather than an anecdote.
    """
    probability = np.clip(np.asarray(probability, dtype=float), 1e-12, 1 - 1e-12)
    odds = probability / (1 - probability)
    distorted = np.exp(shift) * odds ** power
    return distorted / (1 + distorted)


def platt_scale(probability: np.ndarray, y: np.ndarray,
                iterations: int = 2000) -> tuple:
    """Fit ``sigmoid(a * logit(p) + b)`` to repair calibration.

    One-dimensional logistic regression on the model's own log-odds. It
    is monotone, so it cannot change the ranking and therefore cannot
    change the AUC - which is exactly the property that makes it a
    calibration fix rather than a new model.
    """
    probability = np.clip(np.asarray(probability, dtype=float), 1e-12, 1 - 1e-12)
    logit = np.log(probability / (1 - probability)).reshape(-1, 1)
    weights, intercept = fit_logistic(logit, np.asarray(y, dtype=float),
                                      iterations=iterations)
    return float(weights[0]), float(intercept)


def apply_platt(probability: np.ndarray, slope: float, intercept: float) -> np.ndarray:
    probability = np.clip(np.asarray(probability, dtype=float), 1e-12, 1 - 1e-12)
    logit = np.log(probability / (1 - probability))
    return sigmoid(slope * logit + intercept)


