def subgroup_report(cohort, imputed: np.ndarray, missing: np.ndarray) -> list:
    """Predictions for the patients whose value survived, and those whose did not.

    The whole point of splitting them: an overall AUC averages the two
    groups and hides the one the imputation invented values for.
    """
    weights, intercept = fit_logistic(imputed, cohort.y)
    probability = predict(imputed, weights, intercept)
    rows = []
    for label, mask in (("value observed", ~missing), ("value missing", missing)):
        rows.append({
            "label": label, "n": int(mask.sum()),
            "true_risk": float(cohort.risk[mask].mean()),
            "predicted": float(probability[mask].mean()),
            "auc": auc(cohort.y[mask], probability[mask]),
        })
    return rows


