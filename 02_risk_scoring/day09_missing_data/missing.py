def drop_mcar(x: np.ndarray, column: int, rate: float = 0.3,
              seed: int = 0) -> np.ndarray:
    """Missing Completely At Random: a coin flip, unrelated to anything.

    The only mechanism under which throwing away incomplete rows is
    unbiased, and the only one that is easy to reason about. It is also
    the one that almost never describes a clinical dataset.
    """
    if not 0 <= rate <= 1:
        raise ValueError(f"rate must be between 0 and 1, got {rate}")
    rng = np.random.default_rng(seed)
    out = x.astype(float).copy()
    out[rng.random(len(x)) < rate, column] = np.nan
    return out


def drop_mar(x: np.ndarray, column: int, driver: int, rate: float = 0.3,
             seed: int = 0) -> np.ndarray:
    """Missing At Random: missingness depends on an OBSERVED feature.

    Cholesterol is measured less often in younger patients, say. The
    missingness is predictable from data you still have, which is what
    makes it recoverable - an imputation that conditions on ``driver``
    can be unbiased, and one that ignores it cannot.
    """
    rng = np.random.default_rng(seed)
    out = x.astype(float).copy()
    strength = (x[:, driver] - x[:, driver].mean()) / (x[:, driver].std() + 1e-12)
    probability = sigmoid(np.log(rate / (1 - rate)) - 1.2 * strength)
    out[rng.random(len(x)) < probability, column] = np.nan
    return out


def drop_mnar(x: np.ndarray, column: int, rate: float = 0.3,
              seed: int = 0) -> np.ndarray:
    """Missing Not At Random: missingness depends on the VALUE that is gone.

    The test was not ordered because the clinician did not expect it to
    be abnormal, so the missing values are systematically the normal
    ones. Nothing in the observed data identifies the bias, because the
    thing that caused it is the thing you do not have.

    No imputation fixes this. The demo does not find one either.
    """
    rng = np.random.default_rng(seed)
    out = x.astype(float).copy()
    values = x[:, column]
    strength = (values - values.mean()) / (values.std() + 1e-12)
    probability = sigmoid(np.log(rate / (1 - rate)) - 1.2 * strength)
    out[rng.random(len(x)) < probability, column] = np.nan
    return out


def complete_cases(x: np.ndarray, y: np.ndarray) -> tuple:
    """Keep only rows with no missing value. The default in most software."""
    keep = ~np.isnan(x).any(axis=1)
    return x[keep], y[keep]


def impute_mean(x: np.ndarray) -> np.ndarray:
    """Replace each missing value with its column's mean.

    The commonest imputation and the one with the clearest failure mode:
    every imputed patient is placed at the centre of the distribution, so
    the column's variance falls. A regression coefficient is a covariance
    over a variance, and shrinking the denominator's spread while adding
    no signal **attenuates the coefficient towards zero** - which the demo
    measures rather than asserts.
    """
    out = x.astype(float).copy()
    for column in range(out.shape[1]):
        missing = np.isnan(out[:, column])
        if missing.any():
            out[missing, column] = float(np.nanmean(out[:, column]))
    return out


def impute_conditional(x: np.ndarray, column: int, drivers) -> np.ndarray:
    """Predict the missing column from the observed ones by least squares.

    The repair for MAR: if missingness depends on features you still
    have, a model conditioning on them can recover the distribution the
    mean destroys.
    """
    out = x.astype(float).copy()
    missing = np.isnan(out[:, column])
    if not missing.any():
        return out
    drivers = list(drivers)
    observed = ~missing
    design = np.column_stack([np.ones(observed.sum()), out[observed][:, drivers]])
    coefficients, *_ = np.linalg.lstsq(design, out[observed, column], rcond=None)
    predict_design = np.column_stack([np.ones(missing.sum()),
                                      out[missing][:, drivers]])
    out[missing, column] = predict_design @ coefficients
    return out


def add_missing_indicator(x: np.ndarray, column: int) -> np.ndarray:
    """Append a 0/1 column recording whether the value was missing.

    Standard advice, and worth being careful about. If missingness is
    informative - a test not ordered because the patient looked well -
    the indicator carries real signal and the model will use it. That
    improves the score on this dataset and encodes the ordering habits of
    one hospital as if they were biology.

    **Call this before imputing, not after.** Imputation fills the NaNs,
    so an indicator built afterwards is a column of zeros: present,
    harmless-looking, and carrying nothing. It raises rather than
    returning that column, because the first version of this day's demo
    made exactly that mistake and the three imputation strategies came
    out with identical coefficients to three decimal places.
    """
    if not np.isnan(x[:, column]).any():
        raise ValueError(
            f"column {column} has no missing values, so the indicator would be "
            "all zeros - add the indicator before imputing, not after")
    indicator = np.isnan(x[:, column]).astype(float).reshape(-1, 1)
    return np.hstack([x, indicator])


def fit_and_score(x: np.ndarray, y: np.ndarray) -> dict:
    """Fit, then report what Level 2 has learned to ask for."""
    weights, intercept = fit_logistic(x, y)
    probability = predict(x, weights, intercept)
    return {"weights": weights, "intercept": intercept,
            "auc": auc(y, probability),
            "ece": expected_calibration_error(y, probability),
            "brier": brier_score(y, probability), "n": len(y)}


