def moving_average(signal: np.ndarray, window: int, causal: bool = False) -> np.ndarray:
    """The simplest low-pass filter there is: the mean of a sliding window.

    ``causal`` decides whether the window looks backwards only (as it
    must in real time, on a monitor, where the future has not happened
    yet) or is centred on the sample (as it may offline, on a recording).

    That flag is the whole of section 2 below. A causal window of ``w``
    samples delays everything by ``(w-1)/2`` samples, which for a 0.6 s
    window at 250 Hz is 300 ms — longer than a QRS complex, and applied
    to a measurement whose entire purpose is timing.

    >>> moving_average(np.array([0.0, 3.0, 0.0]), window=3).round(3)
    array([1.   , 1.   , 1.   ])
    """
    if window < 1:
        raise ValueError(f"window must be at least 1 sample, got {window}")
    if window == 1:
        return signal.astype(float).copy()
    kernel = np.ones(window) / window
    padded = np.pad(signal.astype(float), (window - 1, window - 1), mode="edge")
    smoothed = np.convolve(padded, kernel, mode="valid")
    if causal:
        return smoothed[:len(signal)]
    offset = (window - 1) // 2
    return smoothed[offset:offset + len(signal)]


def remove_baseline(signal: np.ndarray, fs: float = DEFAULT_FS,
                    window_seconds: float = 0.6,
                    causal: bool = False) -> np.ndarray:
    """High-pass by subtraction: signal minus its own slow average.

    A moving average over a window longer than a beat estimates the
    baseline; subtracting it removes the drift. The window length is the
    only knob and it is a genuine trade, measured in the demo: too short
    and the average starts tracking the QRS itself, which subtracts the
    beat away; too long and slower wander survives.
    """
    window = max(1, int(round(window_seconds * fs)))
    return signal - moving_average(signal, window, causal=causal)


def notch_filter(signal: np.ndarray, fs: float = DEFAULT_FS,
                 frequency: float = 50.0, width: float = 2.0) -> np.ndarray:
    """Zero out one narrow band in the spectrum, then transform back.

    Not how a real monitor does it - a biquad IIR notch is cheaper and
    causal - but it isolates the question this day asks: a notch removes
    everything in its band, including whatever the SIGNAL had there, and
    the demo prices that.
    """
    if width <= 0:
        raise ValueError(f"width must be positive, got {width}")
    if frequency <= 0 or frequency >= fs / 2:
        raise ValueError(f"frequency must be between 0 and {fs / 2}, got {frequency}")
    spectrum = np.fft.rfft(signal)
    frequencies = np.fft.rfftfreq(len(signal), d=1.0 / fs)
    spectrum[np.abs(frequencies - frequency) <= width / 2] = 0.0
    return np.fft.irfft(spectrum, n=len(signal))


def peak_amplitude(signal: np.ndarray, peaks: np.ndarray,
                   half_width: int = 10) -> float:
    """Mean height of the signal at the known R-peak positions.

    Measured at the ground-truth positions rather than at detected ones,
    so it reports what the filter did to the beat rather than what it did
    to the detector.
    """
    if not len(peaks):
        return 0.0
    heights = []
    for position in peaks:
        low = max(0, position - half_width)
        high = min(len(signal), position + half_width + 1)
        heights.append(signal[low:high].max())
    return float(np.mean(heights))


def peak_shift(signal: np.ndarray, peaks: np.ndarray,
               search: int = 60) -> float:
    """Mean samples between each true peak and the nearest local maximum.

    A causal filter delays the whole signal, so the beat arrives late.
    This measures by how much, which for a timing measurement is the
    number that matters more than amplitude.
    """
    if not len(peaks):
        return 0.0
    shifts = []
    for position in peaks:
        low = max(0, position - search)
        high = min(len(signal), position + search + 1)
        if high - low < 3:
            continue
        shifts.append(low + int(np.argmax(signal[low:high])) - position)
    return float(np.mean(shifts)) if shifts else 0.0


def adaptive_threshold_detect(signal: np.ndarray, fs: float = DEFAULT_FS,
                              window_seconds: float = 2.0,
                              factor: float = 0.5,
                              refractory: float = 0.2) -> np.ndarray:
    """Threshold against the LOCAL signal level rather than a fixed one.

    Day 2 showed that baseline wander destroys a fixed threshold while
    leaving the timing untouched. This is the repair: the threshold at
    each sample is ``factor`` of the local maximum, estimated over a
    window a few beats long, so drift moves the threshold with the
    signal.

    It is still not a good detector - Day 4 builds that - but it is the
    minimum change that survives the artefact Day 2 identified, and the
    demo measures whether it does.
    """
    if not 0 < factor < 1:
        raise ValueError(f"factor must be between 0 and 1, got {factor}")
    window = max(3, int(round(window_seconds * fs)))
    envelope = moving_average(np.abs(signal), window)
    local = envelope * 0
    half = window // 2
    for index in range(len(signal)):
        low = max(0, index - half)
        high = min(len(signal), index + half + 1)
        local[index] = signal[low:high].max()
    above = np.where(signal > factor * local)[0]
    if not len(above):
        return np.array([], dtype=int)
    gap = int(round(refractory * fs))
    starts = [above[0]]
    for index in above[1:]:
        if index - starts[-1] >= gap:
            starts.append(index)
    refined = []
    for start in starts:
        end = min(start + gap, len(signal))
        refined.append(start + int(np.argmax(signal[start:end])))
    return np.array(sorted(set(refined)), dtype=int)


