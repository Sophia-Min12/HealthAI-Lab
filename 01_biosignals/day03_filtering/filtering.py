"""Day 3 — Filtering: moving average, and what it does to the peaks.

Three filters against Day 2's three artefacts, and the recurring answer
is that the filter costs something the beat needed.

**Baseline removal** works, and its window is a real trade: 0.1 s keeps
only 82% of the R peak because the average starts tracking the QRS
itself, 2.0 s leaves a quarter of the wander behind. Anywhere between
0.4 and 1.0 s is fine, which is the useful part - the knob is not sharp.

**Smoothing** destroys what it protects. A QRS is 80 ms wide, so a
moving average approaching that width averages the peak against its
neighbours: 83% of the R peak survives a 20 ms window and 20% survives
100 ms. The beat *is* the high-frequency content.

**The causal delay is real and predictable** - a backward-looking mean of
w samples delays by (w-1)/2, which the measurements confirm at small
windows. At large ones they stop confirming it, because the peak has been
flattened away and the measurement is now reporting the distance to some
other local maximum. A measurement whose subject has been destroyed does
not return an error.

**The notch costs nothing here, and that is suspicious.** The synthetic
QRS holds 0.0006% of its energy where a 50 Hz notch cuts, because Day 1
built it from smooth Gaussians. A real QRS has a sharp upstroke and
content past 40 Hz. This is the first place Day 1's caricature changes an
answer, and it is flagged rather than enjoyed.

And the day's own conclusion undercuts it: **two of the three artefacts
are better answered by changing the detector than by filtering.** An
adaptive threshold takes precision under wander from 73% to 100% with no
filter, no window and no delay — within a range. Past 0.8 mV of wander
both detectors collapse and the adaptive one's *sensitivity* is the worse
of the two, because the local maximum it compares against is itself
inflated by the drift.

NOT A MEDICAL DEVICE. Every signal in this repo is generated by it.
"""

