    print("  the two filters that fixed the other artefacts do nothing here,")
    print("  because a burst has energy in every band. Mild smoothing buys")
    print("  sixteen points of precision; twice as much smoothing takes")
    print("  sensitivity from 100% to 25%.")
    print()
    print("  that is the honest answer for motion artefact: there is no")
    print("  filter for it, only a narrow band of mild smoothing that helps")
    print("  a little before it starts deleting beats.")

