def baseline_wander(signal: np.ndarray, fs: float = DEFAULT_FS,
                    amplitude: float = 0.3, frequency: float = 0.25,
                    seed: int | None = None) -> np.ndarray:
    """Slow drift of the whole trace, mostly from breathing.

    A respiration cycle is 12-20 breaths a minute, so 0.2-0.33 Hz, and
    the chest movement drags the electrode baseline with it. The result
    is the trace wandering up and down the screen while the beats
    themselves are untouched.

    That last part matters for everything downstream: wander moves the
    signal, not the **timing**. A detector that finds peaks by position
    is unaffected; one that compares against a fixed amplitude threshold
    fails completely, and Day 3 measures exactly that difference.

    >>> signal, _ = synthesise_ecg(duration=2.0, fs=100.0)
    >>> noisy = baseline_wander(signal, fs=100.0)
    >>> len(noisy) == len(signal)
    True
    """
    if amplitude < 0:
        raise ValueError(f"amplitude must be non-negative, got {amplitude}")
    if frequency <= 0:
        raise ValueError(f"frequency must be positive, got {frequency}")
    time = np.arange(len(signal)) / fs
    phase = 0.0 if seed is None else np.random.default_rng(seed).uniform(0, 2 * np.pi)
    return signal + amplitude * np.sin(2 * np.pi * frequency * time + phase)


def mains_hum(signal: np.ndarray, fs: float = DEFAULT_FS,
              amplitude: float = 0.05, frequency: float = 50.0) -> np.ndarray:
    """Powerline interference: a pure tone at 50 Hz, or 60 Hz in the Americas.

    The frequency is not a detail. A QRS complex has most of its energy
    between 5 and 20 Hz with a tail out past 40, so a 50 Hz notch is
    close to the signal and a 60 Hz notch is a little further away. Day 3
    measures what removing it costs the QRS.

    It is also perfectly periodic, which makes it the one artefact here
    that a filter can remove almost exactly - and the demo shows why that
    is not true of the other two.
    """
    if amplitude < 0:
        raise ValueError(f"amplitude must be non-negative, got {amplitude}")
    if frequency <= 0:
        raise ValueError(f"frequency must be positive, got {frequency}")
    if frequency >= fs / 2:
        raise ValueError(
            f"{frequency} Hz is at or above the Nyquist limit for fs={fs}; "
            "it would alias to a lower frequency rather than appear where it is")
    time = np.arange(len(signal)) / fs
    return signal + amplitude * np.sin(2 * np.pi * frequency * time)


def motion_artefact(signal: np.ndarray, fs: float = DEFAULT_FS,
                    bursts: int = 3, amplitude: float = 1.5,
                    width: float = 0.4, seed: int = 0) -> np.ndarray:
    """Short, large excursions from the electrode moving on the skin.

    The hardest of the three to FILTER, and the reason is its shape
    rather than its size: a burst is broad-band and transient, so it
    overlaps the QRS in both frequency and time. There is no band to
    remove that does not also contain the beat, which is Day 3's problem.

    "Hardest to filter" is not the same as "most damaging", and the demo
    measures the difference. At equal signal-to-noise ratio a burst does
    LESS damage to a threshold detector than continuous noise does,
    because it is confined to a few hundred milliseconds while mains hum
    is present at every sample. I had this the wrong way round until the
    equal-SNR table was run.

    Each burst here is a Gaussian envelope over noise, which is a
    caricature of what an electrode does when a patient shifts - and
    enough to produce excursions taller than the R peak, which is the
    property Day 4's detector has to survive.
    """
    if bursts < 0:
        raise ValueError(f"bursts must be non-negative, got {bursts}")
    if amplitude < 0:
        raise ValueError(f"amplitude must be non-negative, got {amplitude}")
    rng = np.random.default_rng(seed)
    noisy = signal.astype(float).copy()
    time = np.arange(len(signal)) / fs
    duration = len(signal) / fs
    for _ in range(bursts):
        centre = rng.uniform(0.1 * duration, 0.9 * duration)
        envelope = np.exp(-0.5 * ((time - centre) / width) ** 2)
        noisy += amplitude * envelope * rng.normal(0.0, 1.0, size=len(signal))
    return noisy


def sensor_noise(signal: np.ndarray, amplitude: float = 0.02,
                 seed: int = 0) -> np.ndarray:
    """Broadband white noise from the amplifier and the electrode contact."""
    if amplitude < 0:
        raise ValueError(f"amplitude must be non-negative, got {amplitude}")
    rng = np.random.default_rng(seed)
    return signal + rng.normal(0.0, amplitude, size=len(signal))


def dominant_frequency(signal: np.ndarray, fs: float = DEFAULT_FS,
                       ignore_dc: bool = True) -> float:
    """The frequency carrying the most energy, by FFT.

    Used to show that each artefact sits somewhere different in the
    spectrum - which is what makes two of them filterable and one not.
    """
    spectrum = np.abs(np.fft.rfft(signal))
    frequencies = np.fft.rfftfreq(len(signal), d=1.0 / fs)
    if ignore_dc and len(spectrum) > 1:
        spectrum = spectrum[1:]
        frequencies = frequencies[1:]
    return float(frequencies[int(np.argmax(spectrum))])


def band_energy(signal: np.ndarray, low: float, high: float,
                fs: float = DEFAULT_FS) -> float:
    """Fraction of the signal's energy between ``low`` and ``high`` Hz."""
    if low < 0 or high <= low:
        raise ValueError(f"expected 0 <= low < high, got {low} and {high}")
    spectrum = np.abs(np.fft.rfft(signal)) ** 2
    frequencies = np.fft.rfftfreq(len(signal), d=1.0 / fs)
    total = spectrum.sum()
    if total <= 0:
        return 0.0
    selected = (frequencies >= low) & (frequencies < high)
    return float(spectrum[selected].sum() / total)


def threshold_detect(signal: np.ndarray, threshold: float = 0.5,
                     fs: float = DEFAULT_FS, refractory: float = 0.2) -> np.ndarray:
    """The most naive R-peak detector there is: sample above a fixed level.

    Deliberately bad, and deliberately the obvious first idea. It is here
    so that Day 2 can show which noise breaks it and Day 3 can show what
    filtering repairs — a detector nobody would ship, used as an
    instrument.

    ``refractory`` suppresses repeat detections within 200 ms, because
    the heart physically cannot beat twice that fast and without it every
    R peak counts as a dozen.
    """
    if refractory < 0:
        raise ValueError(f"refractory must be non-negative, got {refractory}")
    above = np.where(signal > threshold)[0]
    if not len(above):
        return np.array([], dtype=int)
    gap = int(round(refractory * fs))
    peaks = [above[0]]
    for index in above[1:]:
        if index - peaks[-1] >= gap:
            peaks.append(index)
    # Within each detected region, take the actual maximum.
    refined = []
    for start in peaks:
        end = min(start + gap, len(signal))
        refined.append(start + int(np.argmax(signal[start:end])))
    return np.array(sorted(set(refined)), dtype=int)


def match_peaks(detected: np.ndarray, truth: np.ndarray,
                tolerance_samples: int = 25) -> dict:
    """Score detections against the ground truth Day 1 wrote down.

    A detection counts if it lands within ``tolerance_samples`` of a true
    peak - 100 ms at 250 Hz, which is about the width of a QRS. Each true
    peak can be matched once, so a detector cannot score twice for
    finding the same beat twice.
    """
    truth = list(truth)
    unmatched = set(range(len(truth)))
    true_positive = 0
    for position in detected:
        best = None
        for index in unmatched:
            if abs(truth[index] - position) <= tolerance_samples:
                if best is None or abs(truth[index] - position) < abs(truth[best] - position):
                    best = index
        if best is not None:
            unmatched.discard(best)
            true_positive += 1
    false_positive = len(detected) - true_positive
    false_negative = len(unmatched)
    sensitivity = true_positive / len(truth) if len(truth) else 0.0
    precision = (true_positive / len(detected)) if len(detected) else 0.0
    return {"true_positive": true_positive, "false_positive": false_positive,
            "false_negative": false_negative, "sensitivity": sensitivity,
            "precision": precision}


def amplitude_for_snr(clean: np.ndarray, make_noisy, target_db: float,
                      low: float = 1e-4, high: float = 20.0,
                      steps: int = 60) -> float:
    """The artefact amplitude that produces a chosen signal-to-noise ratio.

    Bisection, because SNR falls monotonically with amplitude for every
    artefact here. It exists so the demo can compare artefacts at *equal*
    SNR rather than at equal amplitude, which is the only comparison that
    says anything about the artefact rather than about the units.
    """
    for _ in range(steps):
        middle = (low + high) / 2
        if signal_to_noise(clean, make_noisy(middle)) > target_db:
            low = middle
        else:
            high = middle
    return (low + high) / 2


