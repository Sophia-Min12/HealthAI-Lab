"""Day 2 — Noise: baseline wander, mains hum, motion artefact.

Day 1 built a signal with exact ground truth. This adds the four things
that ruin a real recording, and measures what each costs a detector.

The central result is that **signal-to-noise ratio does not predict
damage**. Tuned so that every artefact contributes identical noise power,
a naive threshold detector scores 50% precision under mains hum and 80%
under baseline wander — and at -5 dB the spread runs from 28% to 65%. SNR
is out by more than a factor of two.

The ordering is also not the intuitive one. Mains hum and sensor noise,
the two easiest to filter, do *more* damage than motion artefact, which
no filter can touch: a burst is confined to a few hundred milliseconds
while hum is present at every sample. I had that backwards before the
equal-SNR table was run, and the ``motion_artefact`` docstring says so.

One more thing worth separating: sensitivity never moves. Noise adds
energy, so the real beats stay above the line and every failure here is a
false positive. "The detector is 100% sensitive" is true under all four
artefacts and says nothing at all.

NOT A MEDICAL DEVICE. Every signal in this repo is generated by it.
"""

from __future__ import annotations

import numpy as np

# --- reused from day01 -----------------------------------------------------
